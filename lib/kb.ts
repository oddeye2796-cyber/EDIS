// 한국어는 띄어쓰기·조사가 제각각이라 단어 대신 두 글자 조각(bigram)이 겹치는 정도로 찾습니다.
function grams(s: string) {
  const t = s.toLowerCase().replace(/[^0-9a-z가-힣]+/g, " ");
  const out = new Set<string>();
  for (const w of t.split(" ").filter(Boolean)) {
    if (w.length === 1) out.add(w);
    for (let i = 0; i + 1 < w.length; i++) out.add(w.slice(i, i + 2));
  }
  return out;
}

const index = chunks.map((c) => ({ c, title: grams(c.title), body: grams(c.text) }));

export function searchKb(q: string, role?: string, limit = 3) {
  const qg = grams(q);
  if (qg.size === 0) return [];
  return index
    .map(({ c, title, body }) => {
      let s = 0;
      for (const g of qg) s += (title.has(g) ? 3 : 0) + (body.has(g) ? 1 : 0);
      // 내 역할 조각을 조금 앞으로
      if (role && c.roles?.includes(role)) s *= 1.3;
      return { c, s: s / Math.sqrt(qg.size) };
    })
    .filter((r) => r.s > 0.8)
    .sort((a, b) => b.s - a.s)
    .slice(0, limit)
    .map((r) => r.c);
}
